<script>
// Simple script to add labels to table cells for mobile view
(function() {
    // Get all headers
    const headers = [];
    document.querySelectorAll('.custom-table thead th').forEach(th => {
        headers.push(th.innerText.trim());
    });
    
    // Add data-label to each cell
    document.querySelectorAll('.custom-table tbody tr').forEach(row => {
        const cells = row.querySelectorAll('td');
        cells.forEach((cell, index) => {
            if (headers[index]) {
                cell.setAttribute('data-label', headers[index] + ':');
            }
            // Wrap content in span for better styling
            if (!cell.querySelector('span') && cell.childNodes.length) {
                const content = cell.innerHTML;
                cell.innerHTML = `<span>${content}</span>`;
            }
        });
    });
})();
</script>

